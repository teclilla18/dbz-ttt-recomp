#!/usr/bin/env python3
"""Write a [[function]] hints file for one game overlay (see overlays.md).

Function starts come only from facts, never from guessing an entry field:
  1. code start: overlay base + 0x10 (after the 16-byte header);
  2. the header's start-up functions and clean-up record functions;
  3. a stack-frame prologue (addiu sp, sp, -N) right after a `jr ra` + delay
     slot, or at the code start;
  4. main's direct calls into the window that land on a start found by 3, or
     right after a `jr ra` + delay slot in this overlay.
Output is game-derived: write it below build/ only.

  overlay_hints.py <overlay.elf> <main.elf> <out.toml>
"""
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mips_scan as m  # noqa: E402

WINDOW = (0x08A81660, 0x08AEFD30)
JR_RA = 0x03E00008


def is_prologue(w):
    return (w >> 16) == 0x27BD and (w & 0x8000) != 0


def overlay_starts(ovl_segs, main_segs):
    va, blob, _ = ovl_segs[0]
    n = len(blob) // 4
    word = lambda a: struct.unpack_from('<I', blob, a - va)[0] if va <= a < va + 4 * n else None
    starts = {va + 0x10} if n > 4 else set()
    ninit, nfini = struct.unpack_from('<HH', blob, 4)
    pinit, pfini = struct.unpack_from('<II', blob, 8)
    for i in range(ninit if pinit else 0):
        f = word(word(pinit + 4 * i) or 0)
        starts.add(word(pinit + 4 * i))
    for i in range(nfini if pfini else 0):
        rec = word(pfini + 4 * i)
        if rec is not None and word(rec + 8) is not None:
            starts.add(word(rec + 8))
    after_return = set()
    for i in range(6, n):
        a = va + 4 * i
        if word(a - 8) == JR_RA:
            after_return.add(a)
            if word(a):                 # skip zero padding between functions
                starts.add(a)
    # Addresses the overlay itself builds (lui+addiu) or stores as data
    # (vtables, callback tables) that sit on a function boundary.
    hi = va + 4 * n
    boundary = after_return | {a for a in range(va + 0x10, hi, 4)
                                if word(a - 8) is not None and word(a - 8) >> 26 == 2}
    for _, _, x in m.formed_addresses(ovl_segs):
        if va + 0x10 <= x < hi and x % 4 == 0 and (x in boundary or is_prologue(word(x))):
            starts.add(x)
    for i in range(4, n):
        x = struct.unpack_from('<I', blob, 4 * i)[0]
        if va + 0x10 <= x < hi and x % 4 == 0 and (x in boundary or is_prologue(word(x))):
            starts.add(x)
    for pc, w in m.words(main_segs):
        if w >> 26 != 3:
            continue
        t = (pc & 0xF0000000) | ((w & 0x03FFFFFF) << 2)
        if WINDOW[0] <= t < va + 4 * n and (t in after_return or t in starts):
            starts.add(t)
    return sorted(a for a in starts if a is not None and va + 0x10 <= a < va + 4 * n)


def overlay_labels(ovl_segs, starts):
    """Data words that point into the overlay's code but are not function
    starts: switch jump-table targets and similar. They become [[label]]
    hints, i.e. dispatch entries inside their owning function."""
    va, blob, _ = ovl_segs[0]
    n = len(blob) // 4
    known = set(starts)
    out = set()
    for i in range(4, n):
        x = struct.unpack_from('<I', blob, 4 * i)[0]
        if va + 0x10 <= x < va + 4 * n and x % 4 == 0 and x not in known:
            out.add(x)
    return sorted(out)


def main(argv):
    if len(argv) != 4:
        print(__doc__)
        return 2
    starts = overlay_starts(m.load_segments(argv[1]), m.load_segments(argv[2]))
    out = Path(argv[3])
    lines = ['# Generated by tools/overlay_hints.py -- game-derived, keep in build/.',
             '[[function]]', 'at = [']
    lines += [f'  0x{a:08X},' for a in starts] + [']', '']
    out.write_text('\n'.join(lines), encoding='utf-8')
    print(f'{out}: {len(starts)} function starts')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
